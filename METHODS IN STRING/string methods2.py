"""
String Methods: Searching and Replacing
count (): Substring Frequency
find(): Locate First Occurrence
index): Locate (with Error)
replace(): Substitute Substrings

"""

text= "amit is working in google"
print(text.count("i")) # it counts the number of repetative alphabet 
print(text.find("g")) # it  gives you index
print(text.index("g")) # acts same
print(text.replace("g","a"))  # it replaces the previpus alphabet with next one 